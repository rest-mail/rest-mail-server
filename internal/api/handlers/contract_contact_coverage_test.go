// Run the real contract hook against the real handlers and the production
// unique index: otherwise duplicate probes appear to pass on a test-only DB.
func TestCreateContact_ContractProbes(t *testing.T) {
	python, err := exec.LookPath("python3")
	if err != nil {
		t.Skip("contract hooks require python3")
	}
	db := openMsgDeleteTestDB(t)
	if err := db.AutoMigrate(&models.Contact{}); err != nil {
		t.Fatal(err)
	}
	if err := db.Exec(`CREATE UNIQUE INDEX IF NOT EXISTS idx_contacts_mailbox_email ON contacts(mailbox_id, email)`).Error; err != nil {
		t.Fatal(err)
	}
	fx := seedMsgDeleteFixture(t, db, 0)
	t.Cleanup(func() {
		db.Where("mailbox_id = ?", fx.mailbox.ID).Delete(&models.Contact{})
		db.Delete(&fx.mailbox)
		db.Delete(&models.Domain{}, fx.mailbox.DomainID)
	})
	existing := models.Contact{MailboxID: fx.mailbox.ID, Email: "existing@example.com", Name: "Keep me", TrustLevel: "blocked", Source: "manual"}
	if err := db.Create(&existing).Error; err != nil {
		t.Fatal(err)
	}
	h := NewContactHandler(db)
	router := chi.NewRouter()
	router.Use(func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			ctx := context.WithValue(r.Context(), middleware.ClaimsKey, &auth.Claims{AccountID: fx.mailbox.ID})
			next.ServeHTTP(w, r.WithContext(ctx))
		})
	})
	router.Post("/api/v1/accounts/{id}/contacts", h.CreateContact)
	router.Get("/api/v1/accounts/{id}/contacts", h.ListContacts)
	router.Delete("/api/v1/accounts/{id}/contacts/{cid}", h.DeleteContact)
	server := httptest.NewServer(router)
	defer server.Close()
	hookFile, err := filepath.Abs("../../../tests/contract/hooks.py")
	if err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(python, "-c", contactCoverageScript, hookFile, server.URL, uintToStr(fx.mailbox.ID))
	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("contact hook probes: %v\n%s", err, output)
	}
	var results []struct {
		Probe  string `json:"probe"`
		Status int    `json:"status"`
		Want   int    `json:"want"`
	}
	if err := json.Unmarshal(output, &results); err != nil {
		t.Fatalf("decode probes: %v\n%s", err, output)
	}
	if len(results) != 24 {
		t.Fatalf("ran %d probes, want 24", len(results))
	}
	for _, result := range results {
		t.Run(result.Probe, func(t *testing.T) {
			if result.Status != result.Want {
				t.Errorf("status %d, want %d", result.Status, result.Want)
			}
		})
	}
	var preserved models.Contact
	if err := db.First(&preserved, existing.ID).Error; err != nil {
		t.Fatal(err)
	}
	if preserved.Email != existing.Email || preserved.Name != existing.Name || preserved.TrustLevel != existing.TrustLevel {
		t.Fatalf("hook changed an existing contact: %+v", preserved)
	}
}

// The registration shim is the same shape as vertrag's helper module. HTTP
// preparation comes from hooks.py; every probe must keep its generated bytes.
const contactCoverageScript = `
import copy, json, runpy, sys, types, urllib.error, urllib.parse, urllib.request
hooks = types.ModuleType("vertrag_hooks")
callbacks = {"before": {}, "after": {}}
def register(phase):
    def decorator(operation):
        def keep(function):
            callbacks[phase][operation] = function
            return function
        return keep
    return decorator
hooks.before, hooks.after = register("before"), register("after")
hooks.stash = {}
hooks.get_json = lambda transaction, which="request": json.loads(transaction.get(which, {}).get("body") or "{}")
def set_json(transaction, value):
    transaction["request"]["body"] = json.dumps(value, separators=(",", ":"))
hooks.set_json = set_json
sys.modules["vertrag_hooks"] = hooks
runpy.run_path(sys.argv[1])
origin = sys.argv[2]
url = urllib.parse.urlsplit(origin)
account = sys.argv[3]
probes = [
    ("example", account, '{"email":"someone@example.com","name":"","trust_level":"auto"}', 201),
    ("every required property present", account, '{"email":"someone@example.com"}', 201),
    ("required email missing", account, '{}', 422),
    ("email shape", account, '{"email":"someone@example.com"}', 201),
    ("email wrong format", account, '{"email":"not-a-email"}', 422),
    ("email wrong type", account, '{"email":12345}', 400),
    ("name empty", account, '{"email":"someone@example.com","name":""}', 201),
    ("name wrong type", account, '{"email":"someone@example.com","name":12345}', 400),
    ("trust auto", account, '{"email":"someone@example.com","trust_level":"auto"}', 201),
    ("trust trusted", account, '{"email":"someone@example.com","trust_level":"trusted"}', 201),
    ("trust blocked", account, '{"email":"someone@example.com","trust_level":"blocked"}', 201),
    ("trust invalid enum", account, '{"email":"someone@example.com","trust_level":"vertrag-not-in-enum"}', 422),
    ("trust invalid enum fresh email", account, '{"email":"fresh@example.com","trust_level":"vertrag-not-in-enum"}', 422),
    ("trust empty", account, '{"email":"fresh@example.com","trust_level":""}', 422),
    ("account minimum repeated", account, '{"email":"someone@example.com","name":"","trust_level":"auto"}', 201),
    ("account below minimum", "0", '{"email":"someone@example.com"}', 403),
    ("account wrong type", "abc", '{"email":"someone@example.com"}', 400),
    ("account fractional", "1.5", '{"email":"someone@example.com"}', 400),
    ("preexisting contact", account, '{"email":"existing@example.com"}', 409),
    ("preexisting contact repeated", account, '{"email":"existing@example.com"}', 409),
    ("email empty", account, '{"email":""}', 422),
    ("email display name", account, '{"email":"Someone <someone@example.com>"}', 422),
    ("email control character", account, '{"email":"someone@example.com\\r\\nX: injected"}', 422),
    ("email multiple addresses", account, '{"email":"a@example.com,b@example.com"}', 422),
]
results = []
for probe, account_id, body, want in probes:
    transaction = {"fullPath": "/api/v1/accounts/" + account_id + "/contacts",
                   "protocol": url.scheme + ":", "host": url.hostname, "port": str(url.port),
                   "request": {"body": body, "headers": {"Content-Type": "application/json", "Authorization": "probe credential"}}}
    original = copy.deepcopy(transaction)
    callbacks["before"].get("createContact", lambda transaction: None)(transaction)
    assert transaction == original, "hook rewrote the generated probe: " + probe
    json.dumps(hooks.stash)  # The runner transports hook state as JSON.
    request = urllib.request.Request(origin + transaction["fullPath"], data=body.encode(),
                                     headers=transaction["request"]["headers"], method="POST")
    try:
        response = urllib.request.urlopen(request, timeout=10)
    except urllib.error.HTTPError as error:
        response = error
    with response:
        status = response.code
        transaction["real"] = {"body": response.read().decode(), "statusCode": str(status)}
    results.append({"probe": probe, "status": status, "want": want})
print(json.dumps(results))
`
