"""Prove inactive alias setup, cleanup and coverage query preservation."""

import copy
import io
import json
import runpy
import sys
import types
import unittest
import urllib.error
import urllib.parse
from pathlib import Path
from unittest.mock import patch


class AliasRefusalHooksTests(unittest.TestCase):
    def setUp(self):
        module = types.ModuleType("vertrag_hooks")
        self.before = []
        self.after = []
        module.stash = {"setup_admin_tokens": {"http://public.test:8080": "setup-session"}}

        def register(callbacks):
            def operation(name):
                def callback(function):
                    callbacks.append((name, function))
                    return function

                return callback

            return operation

        module.before = register(self.before)
        module.after = register(self.after)
        module.get_json = lambda *_: {}
        module.set_json = lambda *_: None
        with patch.dict(sys.modules, {"vertrag_hooks": module}):
            runpy.run_path(str(Path(__file__).with_name("entrypoint.py")))
        self.prepare = next(
            function for name, function in self.before
            if name == "checkMailboxAddress"
            and function.__name__ == "prepare_alias_refusal"
        )
        self.remove = next(
            function for name, function in self.after
            if name == "checkMailboxAddress"
            and function.__name__ == "remove_alias_refusal"
        )
        self.assertEqual(sum(function == self.prepare for _, function in self.before), 1)
        self.assertIn("look_up_a_hosted_mailbox", [function.__name__ for _, function in self.before])
        self.environment = patch.dict("os.environ", {"CONTRACT_ENDPOINT": "http://public.test:8080"})
        self.environment.start()
        self.addCleanup(self.environment.stop)
        self.transaction = {
            "name": "/api/mailboxes > Check whether an address is a mailbox here (protocol gateways) > 403 > application/json",
            "protocol": "https:", "host": "internal.test", "port": "8443",
            "fullPath": "/api/mailboxes?address=reserved%40example.com",
            "request": {"method": "GET", "headers": {}, "body": ""},
            "expected": {"statusCode": "403", "body": "unchanged"},
        }

    def response(self, body, status=200):
        response = io.BytesIO(json.dumps(body).encode())
        response.status = status
        return response

    def test_setup_and_cleanup_preserve_everything_except_query(self):
        original = copy.deepcopy(self.transaction)
        replies = [self.response({"data": {"id": 42}}, 201),
                   self.response({"data": {"active": False}}), self.response(None, 204)]
        with patch("urllib.request.urlopen", side_effect=replies) as send:
            self.prepare(self.transaction)
            query = urllib.parse.parse_qs(urllib.parse.urlsplit(self.transaction["fullPath"]).query)
            address = query["address"][0]
            self.assertTrue(address.startswith("contract-alias-refused-"))
            self.assertTrue(address.endswith("@restmail.test"))
            original["fullPath"] = self.transaction["fullPath"]
            self.assertEqual(self.transaction, original)
            self.remove(self.transaction)
            self.remove(self.transaction)
        requests = [call.args[0] for call in send.call_args_list]
        self.assertEqual([request.method for request in requests], ["POST", "PATCH", "DELETE"])
        self.assertEqual([request.full_url for request in requests], [
            "http://public.test:8080/api/v1/admin/aliases",
            "http://public.test:8080/api/v1/admin/aliases/42",
            "http://public.test:8080/api/v1/admin/aliases/42",
        ])
        self.assertEqual(json.loads(requests[0].data), {
            "source_address": address, "destination_address": "admin@restmail.test"})
        self.assertEqual(json.loads(requests[1].data), {"active": False})
        self.assertTrue(all(request.get_header("Authorization") == "Bearer setup-session" for request in requests))

    def test_probes_and_other_examples_are_never_rewritten(self):
        for status in ("200", "422", "403"):
            for query in ("", "address=", "address=user%40example.com", "address=null",
                          "address=reserved%40example.com&extra=1", "address=reserved%40example.com"):
                if status == "403" and query == "address=reserved%40example.com":
                    continue
                transaction = copy.deepcopy(self.transaction)
                transaction["expected"]["statusCode"] = status
                transaction["fullPath"] = "/api/mailboxes?" + query
                transaction["request"]["body"] = "generated bytes unchanged"
                original = copy.deepcopy(transaction)
                with patch("urllib.request.urlopen") as send:
                    self.prepare(transaction)
                    self.remove(transaction)
                self.assertEqual(transaction, original)
                send.assert_not_called()

    def test_failed_setup_removes_only_its_own_alias(self):
        failure = urllib.error.HTTPError("fixture", 500, "failed", {}, None)
        with patch("urllib.request.urlopen", side_effect=[
            self.response({"data": {"id": 42}}, 201), failure, self.response(None, 204),
        ]) as send:
            with self.assertRaises(urllib.error.HTTPError):
                self.prepare(self.transaction)
        self.assertEqual(send.call_args.args[0].method, "DELETE")
        self.assertEqual(send.call_args.args[0].full_url, "http://public.test:8080/api/v1/admin/aliases/42")
        self.assertEqual(self.transaction["fullPath"], "/api/mailboxes?address=reserved%40example.com")

    def test_failed_exchange_still_removes_its_fixture(self):
        with patch("urllib.request.urlopen", side_effect=[
            self.response({"data": {"id": 42}}, 201),
            self.response({"data": {"active": False}}), self.response(None, 204),
        ]) as send:
            self.prepare(self.transaction)
            self.transaction["real"] = {"statusCode": "200", "body": "wrong answer"}
            self.remove(self.transaction)
        self.assertEqual(send.call_args.args[0].method, "DELETE")
        self.assertEqual(send.call_args.args[0].full_url, "http://public.test:8080/api/v1/admin/aliases/42")


if __name__ == "__main__":
    unittest.main()
